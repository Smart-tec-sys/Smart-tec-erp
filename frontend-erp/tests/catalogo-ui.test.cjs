const { chromium } = require('/tmp/smarttec-qa-browser/node_modules/playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({headless:true})
  const page = await browser.newPage({viewport:{width:1366,height:950}})
  const errors=[]
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://127.0.0.1:5175/qa-catalogo.html', {waitUntil:'networkidle'})
  const query = page.locator('input[placeholder="Ex.: rolo bk denver"]')
  const select = page.getByLabel('Cor')
  const selected = () => page.getByTestId('selected-json').textContent().then(JSON.parse)
  async function choose(name, search, sku) {
    await query.fill(search)
    const item=page.locator('.product-suggestions button').filter({hasText:name}).filter({hasNotText:'ROLÔ'})
    await item.first().waitFor()
    assert.equal(await item.count(),1, 'Cada coleção deve aparecer uma vez')
    await item.first().click()
    assert.equal((await selected()).id,sku)
  }
  await choose('BK NAPOLES','BK NAPOLES',101)
  assert.equal(await select.locator('option').count(),6, '5 cores + placeholder')
  await select.selectOption('103')
  let value=await selected()
  assert.equal(value.id,103)
  assert.equal(value.cor,'CINZA')
  assert.equal(value.preco,40)
  await choose('TECIDO BK BRISK','TECIDO BK BRISK',201)
  await select.selectOption('202')
  value=await selected()
  assert.equal(value.id,202)
  assert.equal(value.cor,'ALPINO')
  assert.equal(value.preco,44)
  await choose('ROMANA BK BRISK','ROMANA BK BRISK',301)
  value=await selected()
  assert.equal(value.romanaKind,null)
  assert.equal(value.preco,60)
  await choose('TEC PICASSO BK','TEC PICASSO BK',501)
  await select.selectOption('505')
  value=await selected()
  assert.equal(value.id,505)
  assert.equal(value.cor,'GELO')
  assert.equal(value.preco,56)
  await choose('DOUBLE VISION BK. MEXICO','DOUBLE VISION BK. MEXICO',601)
  await select.selectOption('602')
  value=await selected()
  assert.equal(value.id,602)
  assert.equal(value.cor,'BLACK')
  assert.equal(value.preco,46)
  assert.deepEqual(errors,[])
  await page.screenshot({path:'/tmp/smarttec-catalogo-homologacao.png',fullPage:true})
  console.log('PASS teste de navegador real: Nápoles, Brisk, Romana; SKU, cor e preço')
  await browser.close()
})().catch(e=>{console.error(e);process.exit(1)})
