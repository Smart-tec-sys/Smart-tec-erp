const assert=require('node:assert/strict')
const {pathToFileURL}=require('node:url')
const path=require('node:path')
require('node:module').registerHooks({resolve(specifier,context,next){return next(specifier.startsWith('.')&&!path.extname(specifier)?specifier+'.ts':specifier,context)}})
;(async()=>{
 const {technicalSimulationError,technicalItemData}=await import(pathToFileURL(path.join(__dirname,'../src/utils/technicalSimulation.ts')))
 const {emptyProduct}=await import(pathToFileURL(path.join(__dirname,'../src/types/budget.ts')))
 const validation=technicalSimulationError(new Error('API 422: '+JSON.stringify({detail:[{loc:['body','largura'],msg:'Input should be greater than 0',input:0}]})))
 assert.equal(validation,'Revise os campos do cálculo técnico: largura.')
 assert.ok(!validation.includes('detail')); assert.ok(!validation.includes('Input should'))
 assert.equal(technicalSimulationError(new Error('API 422: {"detail":"Medidas inválidas para este modelo."}')),'Medidas inválidas para este modelo.')
 assert.ok(technicalSimulationError(new Error('API 500: private traceback')).includes('temporariamente'))
 assert.ok(!technicalSimulationError(new Error('Failed to fetch')).includes('Failed to fetch'))
 const p={...emptyProduct(1),romanaTetoKind:'MANUAL_CORRENTE',acao_acionamento:'MANUAL_CORRENTE',lado_comando:'DIREITA',comprimento_corrente_sem_fim:'1,75'}
 assert.equal(technicalItemData(p).romana_teto.comprimento_corrente_sem_fim_m,1.75)
 assert.equal(technicalItemData(p).romana_teto.acionamento,'MANUAL_CORRENTE')
 assert.equal(technicalItemData(emptyProduct(2)),null)
 console.log('8 verificações de erros amigáveis e transporte de configuração técnica aprovadas.')
})().catch(e=>{console.error(e);process.exitCode=1})
