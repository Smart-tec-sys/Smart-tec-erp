);
CREATE UNIQUE INDEX uq_grades_variacoes_valores_grade_valor ON public.grades_variacoes_valores (grade_id, lower(btrim(valor)));
CREATE INDEX ix_grades_variacoes_valores_grade_ordem ON public.grades_variacoes_valores (grade_id, ordem, id);
