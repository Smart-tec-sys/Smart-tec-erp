CREATE TABLE public.grades_variacoes (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id INTEGER NOT NULL REFERENCES public.empresas(id),
 nome VARCHAR(120) NOT NULL CHECK (btrim(nome) <> ''),
 descricao TEXT NULL,
 ativo BOOLEAN NOT NULL DEFAULT true,
 ordem INTEGER NOT NULL DEFAULT 0 CHECK (ordem >= 0)
);
CREATE UNIQUE INDEX uq_grades_variacoes_empresa_nome ON public.grades_variacoes (empresa_id, lower(btrim(nome)));
CREATE INDEX ix_grades_variacoes_empresa_ordem ON public.grades_variacoes (empresa_id, ordem, id);
CREATE TABLE public.grades_variacoes_valores (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 grade_id INTEGER NOT NULL REFERENCES public.grades_variacoes(id) ON DELETE RESTRICT,
 valor VARCHAR(150) NOT NULL CHECK (btrim(valor) <> ''),
